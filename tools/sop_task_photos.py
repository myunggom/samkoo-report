    불릿 = [b for b in (it.get("bullets") or []) if b]
    장소 = (t.get("place") or "").strip()
    n = it.get("n") or 1

    두사람 = any(말 in 제목 for 말 in 두사람말)
    틀 = 되풀이장면.get(제목)

    # '공통' · '전 현장' 같은 장소는 그대로 쓰면 "전 현장에서" 라는 말이 안 되는
