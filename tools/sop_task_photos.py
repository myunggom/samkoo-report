def 금지마크(path):
    """다 만든 사진 위에 **빨간 금지 마크**를 얹는다.

    지금 사이트가 쓰는 방식 그대로다. 모델에게 마크를 그리게 하면 모양이
    매번 달라지므로 코드가 똑같은 모양으로 얹는다.
    """
    from PIL import Image, ImageDraw
    im = Image.open(path).convert("RGBA")
    w, h = im.size
    지름 = int(min(w, h) * 0.62)          # 사진의 62% — 지금 사이트와 비슷하다
    굵기 = max(6, int(지름 * 0.085))
    x0, y0 = (w - 지름) // 2, (h - 지름) // 2
    층 = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(층)
    빨강 = (214, 32, 32, 150)              # 반투명 — 밑의 행동이 비쳐 보인다
    여백 = 굵기 // 2 + 1
    d.ellipse([x0 + 여백, y0 + 여백, x0 + 지름 - 여백, y0 + 지름 - 여백],
              outline=빨강, width=굵기)
    # 왼쪽 위 → 오른쪽 아래 빗금. 원 안쪽에 딱 맞게 45도로 긋는다.
    r = (지름 - 굵기) / 2.0
    cx, cy = x0 + 지름 / 2.0, y0 + 지름 / 2.0
    끝 = r * 0.7071
    d.line([cx - 끝, cy - 끝, cx + 끝, cy + 끝], fill=빨강, width=굵기)
    Image.alpha_composite(im, 층).convert("RGB").save(
        path, "JPEG", quality=86, optimize=True, progressive=True)


