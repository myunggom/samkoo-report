def 복장만들기(tid, t):
    """그 작업의 보호구 목록 → (장갑 설명, 더 보여야 할 보호구 글)."""
    이름들 = [(p.get("name") or "") for p in (t.get("ppe") or [])]
    합 = " ".join(이름들)

    장갑 = 장갑설명.get(tid)
    if not 장갑:
        장갑 = 기본장갑
        for 말, 모양 in 장갑모양:
            if any(말 in n for n in 이름들 if "장갑" in n):
                장갑 = 모양
                break

    더 = []
    for 말, 글 in 더보호구:
        if 말 not in 합 or 글 in 더:
            continue
        # 호흡 보호구는 한 종류만. 송기 · 공기호흡기 · 방독 · 방진 · 보건용이
        # 한 작업에 여러 개 적힌 경우가 있어, 먼저 잡힌 것 하나만 쓴다.
        # (열쇠말만 보던 예전 규칙은 '송기' · '방독' 을 걸러내지 못했다.)
        if 글 in 호흡보호구 and any(x in 호흡보호구 for x in 더):
            continue
        # 얼굴 가리개도 한 종류만. '용접용 보안면' 이 적힌 작업은 '안면' 규칙에도
        # 걸려서, 검은 용접면과 투명 안면보호구를 둘 다 쓴 그림이 나왔다.
        if 말 in ("안면", "아크") and any(x in 더 for x in 얼굴가리개):
            continue
        if 말 == "용접용 보안면":
            더 = [x for x in 더 if x not in 얼굴가리개]
        # 앞치마도 하나만. '불침투성 앞치마' 가 적힌 작업은 '앞치마' 규칙에도
        # 걸려서 노란 앞치마와 가죽 앞치마를 둘 다 두른 그림이 나왔다.
        if "앞치마" in 말 and any("앞치마" in x for x in 더):
            continue
        더.append(글)
    return 장갑, "\n".join(더)

