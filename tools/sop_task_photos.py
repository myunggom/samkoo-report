def 사람몫(path):
    """남색 작업복이 화면에서 차지하는 몫. 사람이 잘렸는지 가늠한다.

    옷 색으로 세는 것이라 흰 보호복 작업에서는 낮게 나온다. 그래서
    이 숫자는 **판정이 아니라 눈으로 볼 목록**을 뽑는 데만 쓴다.
    """
    try:
        import numpy as np
        from PIL import Image
    except ImportError:
        return None
    try:
        a = np.asarray(Image.open(path).convert("RGB")
                       .resize((320, 213))).astype(np.int16)
    except Exception:                                        # noqa: BLE001
        return None
    R, G, B = a[:, :, 0], a[:, :, 1], a[:, :, 2]
    밝기 = (R + G + B) / 3.0
    남색 = (B > R + 18) & (B > G + 8) & (밝기 < 135) & (밝기 > 18)
    return float(남색.mean())


def 사람봤나(만든것):
    """만든 사진 중 **눈으로 봐야 할 것**을 골라 준다. 빈 목록이면 조용하다."""
    볼것 = []
    for n, path in 만든것:
        몫 = 사람몫(path)
        if 몫 is None:
            continue
        if 몫 < 0.03:
            볼것.append("%s번 — 사람이 화면에 거의 없습니다 (옷 %0.0f%%)"
                        % (n, 몫 * 100))
        elif 몫 > 0.28:
            볼것.append("%s번 — 너무 들이대 머리나 발이 잘렸을 수 있습니다 "
                        "(옷 %0.0f%%)" % (n, 몫 * 100))
    return 볼것


