def 저장(데이터, path, 가로=1600):
    """받은 그림을 가로 1600px JPEG 로 줄여 저장한다."""
    import io as _io
    from PIL import Image
    im = Image.open(_io.BytesIO(데이터)).convert("RGB")
    w, h = im.size
    if w > 가로:
        im = im.resize((가로, round(h * 가로 / w)), Image.LANCZOS)
