def 부위찾기(t, 글):
    """그 조치와 맞는 '각부 명칭' 물건을 찾는다.

    작업마다 각부 명칭 6개가 구체적인 물건 이름으로 적혀 있다.
    장면에 그 물건을 집어넣으면 12장이 서로 다른 것을 비추게 된다.
    단, 흔한 말로 맞히면 엉뚱한 물건이 붙으므로 **그 작업에서만 쓰는 말**로만
    맞힌다.
    """
    for x in (t.get("parts") or {}).get("items") or []:
        이름 = (x.get("name") or "").strip()
        if not 이름:
            continue
        for 조각 in [w for w in 이름.replace("·", " ").split()
                   if len(w) >= 2 and w not in 흔한말]:
            if 조각 in 글:
                return 이름
    return ""


def 이가(말):
    """받침이 있으면 '이', 없으면 '가'. 조사가 틀리면 글이 허술해 보인다.

    '예취날 (칼날)' 처럼 괄호로 끝나는 이름이 있어 **맨 끝 글자가 아니라
    마지막 한글 글자**를 봐야 한다.
    """
    for 끝 in reversed(말 or ""):
        if "가" <= 끝 <= "힣":
            return "이" if (ord(끝) - 0xAC00) % 28 else "가"
        if 끝.isalnum():
            return "이"
    return "가"


def 장면만들기(tid, t, it, 설비있음):
    """조치 한 건 → (장면 글, 두 사람인가, 가로세로)."""
    제목 = (it.get("name") or "").strip()
    불릿 = [b for b in (it.get("bullets") or []) if b]
    장소 = (t.get("place") or "").strip()
    n = it.get("n") or 1

    두사람 = any(말 in 제목 for 말 in 두사람말)
    틀 = 되풀이장면.get(제목)

    # '공통' · '전 현장' 같은 장소는 그대로 쓰면 "전 현장에서" 라는 말이 안 되는
    # 문장이 된다. 진짜 방 이름일 때만 쓴다.
    어디 = ("%s에서 " % 장소) if (장소 and len(장소) <= 12
                             and 장소 not in 막연한장소) else ""
    누가 = ("주인공과 보조자가 %s함께 " % 어디) if (틀[1] if 틀 else 두사람) \
        else ("주인공이 %s" % 어디)

    if 틀:
        장면 = [누가 + 틀[0]]
        두사람 = 틀[1]
    else:
        # 세부 문구를 그대로 동작으로 쓴다. 자세표는 보조로만 쓴다.
        장면 = [누가 + 동작으로(불릿[0] if 불릿 else 제목) + "."]
        장면.append(구도표[(n - 1) % len(구도표)])
        부위 = 부위찾기(t, 제목 + " " + " ".join(불릿))
        if 부위:
            장면.append("화면에는 **%s**%s 또렷하게 보입니다." % (부위, 이가(부위)))
        if len(불릿) > 1:
            장면.append("곁들여 보여 줄 것 : %s" % 불릿[1])

    if 설비있음:
        장면.append("함께 보이는 설비는 **첨부한 참조 사진의 그 설비**입니다. "
                  "생김새와 색을 그대로 옮기고, 다른 기계를 그리지 마세요.")
    return " ".join(장면), 두사람, "3:2"


def 장면표만들기(tid, t):
    """그 작업의 조치 전부에 대한 장면표. 손으로 쓴 것이 있으면 그것을 쓴다."""
    손 = SCENES_ALL.get(tid) or {}
    설비있음 = bool(설비사진.get(tid))
    표 = {}
    for sec in t.get("guide") or []:
        for it in sec.get("items") or []:
            n = it.get("n")
            표[n] = 손[n] if n in 손 else 장면만들기(tid, t, it, 설비있음)
    return 표

